// Writes icons.caju: the Lucide icons the original site uses (lucide-react, the same version), as
// ui nodes with the same markup lucide-react renders.
//   node tools/export-icons.mjs [cajulang-site dir]
import { writeFileSync } from "node:fs"
import { join, dirname } from "node:path"
import { fileURLToPath } from "node:url"

const here = dirname(fileURLToPath(import.meta.url))
const site = process.argv[2] || join(here, "../../cajulang-site")
const dir = join(site, "node_modules/lucide-react/dist/esm/icons")
// the name the site uses -> the icon file (and the extra class lucide-react adds for an alias)
const icons = {
  menu: "menu", languages: "languages", moon: "moon", sun: "sun", check: "check", copy: "copy",
  download: "download", "chevron-right": "chevron-right", "chevron-left": "chevron-left",
  "arrow-right": "arrow-right", "arrow-down": "arrow-down", play: "play", "loader-2": "loader-circle",
  square: "square", "link-2": "link-2", "rotate-ccw": "rotate-ccw", plus: "plus", x: "x", user: "user",
  bot: "bot", wrench: "wrench",
}
const q = (s) => JSON.stringify(s)
let out = "# Generated by tools/export-icons.mjs from lucide-react: do not edit.\nimport ui \"../caju-ui/ui\"\n\n"
out += "# a Lucide icon, with the markup lucide-react renders (class: lucide lucide-<name> and cls)\n"
out += "export fn icon(name: str, cls: str) -> *ui.Node {\n  c := \"lucide lucide-\" + name\n"
out += "  if name == \"loader-2\" { c = \"lucide lucide-loader-circle lucide-loader-2\" }\n"
out += "  if cls != \"\" { c = c + \" \" + cls }\n"
out += "  attrs := []ui.Attr{ui.a(\"xmlns\", \"http://www.w3.org/2000/svg\"), ui.a(\"width\", \"24\"), ui.a(\"height\", \"24\"), ui.a(\"viewBox\", \"0 0 24 24\"), ui.a(\"fill\", \"none\"), ui.a(\"stroke\", \"currentColor\"), ui.a(\"stroke-width\", \"2\"), ui.a(\"stroke-linecap\", \"round\"), ui.a(\"stroke-linejoin\", \"round\"), ui.a(\"class\", c), ui.a(\"aria-hidden\", \"true\")}\n"
out += "  return ui.h(\"svg\", attrs, shapes(name))\n}\n\nfn shapes(name: str) -> []*ui.Node {\n  switch name {\n"
for (const [name, file] of Object.entries(icons)) {
  const { __iconData } = await import(join(dir, file + ".mjs"))
  const node = __iconData.node
  const parts = node.map(([tag, attrs]) => {
    const as = Object.entries(attrs).filter(([k]) => k !== "key").map(([k, v]) => `ui.a(${q(k)}, ${q(String(v))})`)
    return `ui.h(${q(tag)}, []ui.Attr{${as.join(", ")}}, nil)`
  })
  out += `  case ${q(name)}: return []*ui.Node{${parts.join(", ")}}\n`
}
out += "  }\n  return nil\n}\n"
writeFileSync(join(here, "../icons.caju"), out)
console.log("icons.caju:", Object.keys(icons).length, "icons")
